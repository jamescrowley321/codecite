    /// Prints how many sections and steps a real document has, and the
    /// sections with the most steps, for the PR description.
    fn report(name: &str, doc: &SpecDocument) {
        let steps: usize = doc.sections.iter().map(|s| s.steps.len()).sum();
        let mut most: Vec<_> = doc
            .sections
            .iter()
            .filter(|s| !s.steps.is_empty())
            .map(|s| (s.steps.len(), s.number.as_str()))
            .collect();
        most.sort_by(|a, b| b.cmp(a));
        most.truncate(5);
        println!(
            "{name}: {} sections, {steps} steps; most steps: {most:?}; relations: {:?}",
            doc.sections.len(),
            doc.relations
        );
    }

    #[test]
    fn deep_nesting_does_not_overflow_the_stack() {
        // The walk is iterative, so 5,000 nested elements fit in a 256 KiB
        // stack, where a recursive walk would overflow. The depth stays low
        // because html5ever's parse is quadratic in nesting depth.
        let depth = 5_000;
        let html = format!(
            "<section id=\"section-1\"><h2><a class=\"section-number\">1. </a>\
             <a class=\"section-name\">Deep</a></h2>{}x{}</section>",
            "<div>".repeat(depth),
            "</div>".repeat(depth)
        );
        let doc = std::thread::Builder::new()
            .stack_size(256 * 1024)
            .spawn(move || split_spec(&html))
            .unwrap()
            .join()
            .unwrap()
            .unwrap();
        assert_eq!(doc.sections.len(), 1);
        assert!(doc.sections[0].text.ends_with('x'));
    }
